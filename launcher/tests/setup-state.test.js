'use strict';
const assert=require('node:assert/strict');
const {setupStep}=require('../assets/setup-state.js');
const fresh={supported:true,termux:false,linked:false,installed:false,jobs:{},health:{}};
assert.equal(setupStep(fresh).action,'prepare');
assert.equal(setupStep({...fresh,jobs:{termux:{state:'running'}}}).tab,'downloads');
assert.equal(setupStep({...fresh,jobs:{termux:{state:'ready'}}}).label,'Termuxをインストール');
assert.equal(setupStep({...fresh,termux:true}).action,'openTermux');
assert.equal(setupStep({...fresh,termux:true,termuxOpened:true}).action,'repairLink');
const linked={...fresh,termux:true,termuxOpened:true,linked:true};
assert.equal(setupStep(linked).action,'prepare');
assert.equal(setupStep({...linked,jobs:{bolt:{state:'running'}}}).tab,'downloads');
assert.equal(setupStep({...linked,jobs:{bolt:{state:'error',error_code:'termux_link'}}}).action,'repairLink');
assert.equal(setupStep({...linked,jobs:{bolt:{state:'paused'}}}).label,'続きから再開');
assert.equal(setupStep({...linked,installed:true,runtimeCurrent:false}).action,'prepare');
const installed={...linked,installed:true,runtimeCurrent:true};
assert.equal(setupStep(installed).action,'openChat');
assert.match(setupStep(installed).detail,/起動します/);
assert.doesNotMatch(setupStep(installed).detail,/画像.*でき/);
assert.match(setupStep({...installed,health:{gemma:true}}).detail,/接続しています/);
assert.equal(setupStep({...installed,supported:false}).key,'unsupported');
